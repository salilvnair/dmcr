import { useState, useCallback, useEffect, useRef } from 'react';
import { PrismLight as SyntaxHighlighter } from 'react-syntax-highlighter';
import sqlLang from 'react-syntax-highlighter/dist/esm/languages/prism/sql';
import jsonLang from 'react-syntax-highlighter/dist/esm/languages/prism/json';
import { oneLight, vscDarkPlus } from 'react-syntax-highlighter/dist/esm/styles/prism';
import { ButtonView, IconButtonView, CheckCircleIcon, CheckIcon, CloseIcon, CopyIcon, EyeIcon, FolderOpenIcon, GithubMarkIcon, RenameIcon, SaveIcon, TrashIcon, WarningTriangleIcon, XCircleIcon } from '@salilvnair/dui';
import { postMsg } from '../vscode';
import { prettyJson } from '../utils/prettyJson';
import { useReleaseFields } from './ReleaseFields';
import SelfCheckBanner, { type SelfCheck } from './SelfCheckBanner';
import './ChangeCard.css';

SyntaxHighlighter.registerLanguage('sql', sqlLang);
SyntaxHighlighter.registerLanguage('json', jsonLang);

export type ChangeData = {
  changeName: string;
  deploySql: string;
  verifySql: string;
  revertSql: string;
  metaJson?: string;
  suggestedLocation?: string;
  selfCheck?: SelfCheck;
};

type LintState = { ok: boolean; msg: string } | null;
type SqlTab = 'deploy' | 'verify' | 'revert' | 'meta';

type Props = {
  change: ChangeData;
  form: string;
  /** Called once the change is saved to the workspace (the form resets its per-change options) */
  onSaved?: () => void;
};

// The form pages unmount while their tab is hidden. Keep what matters about a card — that it
// was saved (so it is not offered for a second save) and unsaved edits — with the change itself.
const cardMemory = new WeakMap<ChangeData, { saved?: { folderRel: string }; editMap?: Partial<Record<SqlTab, string>> }>();

export { PROJECT_TYPE_COLORS } from './ReleaseFields';

export default function ChangeCard({ change, form, onSaved }: Props) {
  const [activeTab, setActiveTab] = useState<SqlTab>('deploy');
  const [lintMap, setLintMap] = useState<Record<SqlTab, LintState>>({ deploy: null, verify: null, revert: null, meta: null });
  const [location, setLocation] = useState(change.suggestedLocation || '');
  const [saving, setSaving] = useState(false);
  const [saved, setSavedState] = useState<{ folderRel: string } | null>(() => cardMemory.get(change)?.saved ?? null);
  const setSaved = (v: { folderRel: string } | null) => { cardMemory.set(change, { ...cardMemory.get(change), saved: v ?? undefined }); setSavedState(v); };
  const [saveError, setSaveError] = useState('');
  const [showDiscard, setShowDiscard] = useState(false);
  const [isLightTheme, setIsLightTheme] = useState(() => document.documentElement.dataset.theme === 'light');
  const [editing, setEditing] = useState(false);
  const [editMap, setEditMapState] = useState<Partial<Record<SqlTab, string>>>(() => cardMemory.get(change)?.editMap ?? {});
  const setEditMap = (f: (prev: Partial<Record<SqlTab, string>>) => Partial<Record<SqlTab, string>>) => setEditMapState(prev => { const next = f(prev); cardMemory.set(change, { ...cardMemory.get(change), editMap: next }); return next; });
  const [copied, setCopied] = useState(false);
  const [copiedTab, setCopiedTab] = useState<SqlTab | null>(null);
  const [committing, setCommitting] = useState(false);
  const [commitDone, setCommitDone] = useState(false);
  const [commitInfo, setCommitInfo] = useState('');
  const [commitError, setCommitError] = useState('');
  // After saving: the project / requested by / kind meta.json holds, so a later edit can be saved too
  const [savedRelease, setSavedRelease] = useState<{ project: string; requestedBy: string; kind: string; environments?: string } | null>(null);
  const [savingDetails, setSavingDetails] = useState(false);
  const commitMsgRef = useRef<string | undefined>(undefined);
  // DDL, DML and Freeform pages stay mounted together, so several ChangeCards can be
  // listening at once. Every request carries this id and only matching replies are applied.
  const requestIdRef = useRef(`changecard-${form}-${Math.random().toString(36).slice(2, 10)}`);

  // Release fields: project (from releases.json), the developer who asked, and an optional kind
  const { fields: releaseFields, releaseMeta, dbaName, remember: rememberRelease } = useReleaseFields();

  const releaseRef = useRef({ project: '', requestedBy: '', kind: '', environments: '' });
  const envKey = (releaseMeta.environments ?? []).join(',');
  releaseRef.current = { project: releaseMeta.project ?? '', requestedBy: releaseMeta.requestedBy ?? '', kind: releaseMeta.kind ?? '', environments: envKey };

  const isDanger = change.changeName?.includes('danger_') ?? false;
  const isRepeatable = change.changeName?.startsWith('R__') ?? false;

  // Build meta.json content
  const metaContent = prettyJson(change.metaJson) || JSON.stringify({
    change_id: change.changeName,
    description: `Generated by DMCR ${form} form`,
    requires: [],
    tags: [],
    author: ''
  }, null, 2);

  const sqlMap: Record<SqlTab, string> = {
    deploy: change.deploySql || '',
    verify: change.verifySql || '',
    revert: change.revertSql || '',
    meta: metaContent,
  };

  // Effective SQL for current tab (uses edited version if present)
  const effectiveSql = (tab: SqlTab) => editMap[tab] ?? sqlMap[tab];

  // Request lint for SQL tabs on mount; validate meta.json separately
  useEffect(() => {
    const sqlTabs: SqlTab[] = ['deploy', 'verify', 'revert'];
    sqlTabs.forEach((tab, i) => {
      setTimeout(() => {
        postMsg({ type: 'lintSql', payload: { id: tab, which: tab, sql: sqlMap[tab] || '', requestId: requestIdRef.current } });
      }, 200 + i * 120);
    });
    // Validate meta.json locally (no server lint needed)
    try {
      JSON.parse(metaContent);
      setLintMap(prev => ({ ...prev, meta: { ok: true, msg: '' } }));
    } catch (e: any) {
      setLintMap(prev => ({ ...prev, meta: { ok: false, msg: e.message || 'Invalid JSON' } }));
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [change]);

  const onSavedRef = useRef(onSaved);
  onSavedRef.current = onSaved;
  // Listen for lint results, saved, saveError, folderPicked
  useEffect(() => {
    const handler = (event: MessageEvent) => {
      const msg = event.data;
      if (!msg) return;
      const mine = msg.payload?.requestId === requestIdRef.current;
      if (msg.type === 'lintResult') {
        if (!mine) return;
        const id = msg.payload?.id;
        if (id === 'deploy' || id === 'verify' || id === 'revert') {
          setLintMap(prev => ({ ...prev, [id]: { ok: !!msg.payload.ok, msg: msg.payload.msg || '' } }));
        }
      } else if (msg.type === 'saved' && msg.payload?.folderId && mine) {
        setSaving(false);
        setSaved({ folderRel: msg.payload.folderRel || msg.payload.folderId || '' });
        setSavedRelease({ ...releaseRef.current });
        onSavedRef.current?.();
      } else if (msg.type === 'releaseData' && mine && (msg.payload?.saved || msg.payload?.saveError)) {
        // Save details (updateChangeMeta) answered: meta.json now holds the card's project / requester / kind
        setSavingDetails(false);
        if (msg.payload.saveError) { setSaveError(msg.payload.saveError); return; }
        setSavedRelease({ ...releaseRef.current });
        setCommitDone(false);
        commitMsgRef.current = `chore(dmcr): update project / requested by / kind of ${msg.payload.saved}`;
      } else if (msg.type === 'saveError' && mine) {
        setSaving(false);
        setSaveError(msg.payload?.msg || 'Save failed.');
      } else if (msg.type === 'folderPicked' && mine) {
        setLocation(msg.payload?.path || msg.payload?.folderRel || '');
      } else if (msg.type === 'commitResult' && mine) {
        setCommitting(false);
        if (msg.payload?.ok) {
          setCommitDone(true);
          setCommitError('');
          setCommitInfo(msg.payload?.pushed ? `Committed ${msg.payload?.commitHash ?? ''} and pushed` : msg.payload?.committed ? `Committed ${msg.payload?.commitHash ?? ''}${msg.payload?.note ? ' locally (no git remote)' : ''}` : 'Nothing new to commit');
        } else {
          setCommitError(msg.payload?.error || 'Commit failed.');
        }
      }
    };
    window.addEventListener('message', handler);
    return () => window.removeEventListener('message', handler);
  }, []);

  useEffect(() => {
    const root = document.documentElement;
    const syncTheme = () => setIsLightTheme(root.dataset.theme === 'light');
    syncTheme();

    const observer = new MutationObserver(syncTheme);
    observer.observe(root, { attributes: true, attributeFilter: ['data-theme'] });
    return () => observer.disconnect();
  }, []);

  const handleSave = useCallback(() => {
    setSaving(true);
    setSaveError('');
    postMsg({
      type: 'saveChange',
      payload: {
        changeName: change.changeName,
        deploySql: editMap.deploy ?? change.deploySql,
        verifySql: editMap.verify ?? change.verifySql,
        revertSql: editMap.revert ?? change.revertSql,
        metaJson: editMap.meta ?? metaContent,
        location: location.trim(),
        releaseMeta,
        requestId: requestIdRef.current,
      },
    });
    rememberRelease();
  }, [change, location, metaContent, editMap, releaseMeta.project, releaseMeta.requestedBy, releaseMeta.kind, envKey, rememberRelease]);

  const handleCopy = useCallback(() => {
    navigator.clipboard.writeText(effectiveSql(activeTab)).then(() => {
      setCopied(true);
      setTimeout(() => setCopied(false), 1500);
    });
  }, [activeTab, editMap, sqlMap]);

  const handleBrowse = useCallback(() => {
    postMsg({ type: 'browseFolder', payload: { requestId: requestIdRef.current } });
  }, []);

  const handleReveal = useCallback(() => {
    if (saved?.folderRel) postMsg({ type: 'revealFolder', payload: { folderRel: saved.folderRel } });
  }, [saved]);

  const handleCommit = useCallback(() => {
    if (!saved?.folderRel || committing || commitDone) return;
    setCommitting(true);
    setCommitError('');
    postMsg({ type: 'manualCommitAndPush', payload: { folderRel: saved.folderRel, requestId: requestIdRef.current, message: commitMsgRef.current } });
  }, [saved, committing, commitDone]);

  // Project / requested by / kind changed after saving: write them to the saved meta.json
  const detailsChanged = !!saved && !!savedRelease && (savedRelease.project !== (releaseMeta.project ?? '')
    || savedRelease.requestedBy !== (releaseMeta.requestedBy ?? '') || savedRelease.kind !== (releaseMeta.kind ?? '')
    || (savedRelease.environments ?? '') !== envKey);
  const handleSaveDetails = useCallback(() => {
    const changeId = (saved?.folderRel ?? '').split(/[\\/]/).pop() ?? '';
    if (!changeId) return;
    setSavingDetails(true);
    setSaveError('');
    postMsg({ type: 'updateChangeMeta', payload: { changeId, requestId: requestIdRef.current,
      patch: { project: releaseMeta.project || null, requested_by: releaseMeta.requestedBy || null, kind: releaseMeta.kind || null, environments: releaseMeta.environments ?? null } } });
    rememberRelease();
  }, [saved, releaseMeta.project, releaseMeta.requestedBy, releaseMeta.kind, envKey, rememberRelease]);

  const handleClose = useCallback(() => {
    if (saved) {
      // Already saved — wipe the form and return to a fresh form state.
      postMsg({ type: 'cancel', payload: { form, reset: true } });
    } else {
      setShowDiscard(true);
    }
  }, [form, saved]);

  const handleDiscardConfirm = useCallback(() => {
    setShowDiscard(false);
    postMsg({ type: 'cancel', payload: { form, reset: true } });
  }, [form]);

  const handleDiscardCancel = useCallback(() => {
    setShowDiscard(false);
  }, []);

  const lint = lintMap[activeTab];
  const changeNameValid = !change.changeName || /^(R__)?[a-z][a-z0-9_]*$/.test(change.changeName);

  return (
    <div className="cc-screen">
      <div className="change-card">
        {/* Header */}
        <div className="cc-header">
          <div className="cc-icon">
            <svg width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.8" strokeLinecap="round" strokeLinejoin="round"><path d="M22 19a2 2 0 0 1-2 2H4a2 2 0 0 1-2-2V5a2 2 0 0 1 2-2h5l2 3h9a2 2 0 0 1 2 2z"/></svg>
          </div>
          <div className="cc-title">
            <div className="cc-name-row">
              <div className="cc-name">{change.changeName || 'change'}</div>
              {isDanger && <span className="cc-chip cc-chip-danger">danger_</span>}
              {isRepeatable && <span className="cc-chip cc-chip-repeatable">R__ repeatable</span>}
            </div>
            {!changeNameValid && (
              <div className="cc-name-warn"><WarningTriangleIcon size={12} style={{ verticalAlign: '-2px', marginRight: 5 }} />Change name must start with a letter and contain only lowercase letters, digits, and underscores</div>
            )}
            <div className="cc-subtitle">Review SQL, then save to your workspace</div>
          </div>
        </div>

        {/* Save location */}
        <div className="cc-loc">
          <label>Save location (relative to workspace root)</label>
          <div className="cc-loc-row">
            <input
              type="text"
              className="cc-loc-input"
              value={location}
              onChange={e => setLocation(e.target.value)}
              placeholder="db/changes (leave empty for workspace setting)"
            />
            <ButtonView type="button" variant="secondary" iconLeft={<FolderOpenIcon size={14} color="var(--dm-c-f59e0b)" />} label="Browse" onClick={handleBrowse} title="Browse folder" style={{ flexShrink: 0 }} />
          </div>
        </div>

        <SelfCheckBanner check={change.selfCheck} />

        {/* Release: project, requested by, kind */}
        {releaseFields}

        {/* SQL Tabs */}
        <div className="cc-tabs">
          {(['deploy', 'verify', 'revert', 'meta'] as SqlTab[]).map(tab => (
            <button
              key={tab}
              type="button"
              className={`cc-tab cc-tab--${tab}${activeTab === tab ? ' active' : ''}${tab === 'meta' ? ' cc-tab-meta' : ''}`}
              onClick={() => setActiveTab(tab)}
            >
              <span className="cc-tab-label">{tab === 'meta' ? 'meta.json' : `${tab}.sql`}</span>
              <span
                className={`cc-tab-copy${copiedTab === tab ? ' cc-tab-copy--copied' : ''}`}
                title={copiedTab === tab ? 'Copied!' : `Copy ${tab === 'meta' ? 'meta.json' : tab + '.sql'}`}
                onClick={e => {
                  e.stopPropagation();
                  navigator.clipboard.writeText(effectiveSql(tab)).then(() => {
                    setCopiedTab(tab);
                    setTimeout(() => setCopiedTab(null), 1500);
                  });
                }}
              >
                {copiedTab === tab ? <CheckIcon size={11} color="var(--dm-c-4ade80)" /> : <CopyIcon size={11} />}
              </span>
            </button>
          ))}
          <span className="cc-tabs-actions">
            <IconButtonView size="sm" variant={editing ? 'filled' : 'ghost'} active={editing}
              icon={editing ? <EyeIcon size={13} /> : <RenameIcon size={13} />}
              tooltip={editing ? 'Back to view mode' : 'Edit SQL'} onClick={() => setEditing(e => !e)} />
            <IconButtonView size="sm" variant="ghost"
              icon={copied ? <CheckIcon size={13} color="var(--dm-c-4ade80)" /> : <CopyIcon size={13} />}
              tooltip={copied ? 'Copied' : 'Copy to clipboard'} onClick={handleCopy} />
          </span>
        </div>

        {/* SQL display with syntax highlighting + edit mode */}
        <div className="cc-sql-wrap">
          {editing ? (
            <textarea
              className="cc-sql-editor"
              value={effectiveSql(activeTab)}
              onChange={e => setEditMap(prev => ({ ...prev, [activeTab]: e.target.value }))}
              spellCheck={false}
            />
          ) : (
            <SyntaxHighlighter
              language={activeTab === 'meta' ? 'json' : 'sql'}
              style={isLightTheme ? oneLight : vscDarkPlus}
              customStyle={{
                margin: 0,
                padding: '14px 16px',
                background: 'transparent',
                fontSize: '12.5px',
                lineHeight: '1.6',
                fontFamily: "ui-monospace,'Cascadia Code','JetBrains Mono',Consolas,monospace",
                overflow: 'auto',
                flex: 1,
                minHeight: 0,
                whiteSpace: 'pre-wrap',
                wordBreak: 'break-word',
                overflowX: 'hidden',
              }}
              wrapLongLines
              // the theme puts white-space: pre on <code>; long lines (meta.json description, comments) wrap instead
              codeTagProps={{ style: { whiteSpace: 'pre-wrap', wordBreak: 'break-word', overflowWrap: 'anywhere' } }}
            >
              {effectiveSql(activeTab)}
            </SyntaxHighlighter>
          )}
        </div>

        {dbaName === '' && (
          <div className="cc-err"><WarningTriangleIcon size={12} style={{ verticalAlign: '-2px', marginRight: 5 }} />Set your DBA name in Settings &gt; DMCR Config before saving: every change records who created it.</div>
        )}

        {/* Save error */}
        {saveError && <div className="cc-err">{saveError}</div>}

        {/* Footer: lint + actions */}
        <div className="cc-footer">
          <div className={`cc-lint${lint ? (lint.ok ? ' ok' : ' err') : ''}`}>
            {!lint && <span className="cc-lint-spinner" />}
            <span style={{ display: 'inline-flex', alignItems: 'center', gap: 5 }}>
              {(() => {
                const fname = activeTab === 'meta' ? 'meta.json' : `${activeTab}.sql`;
                if (!lint) return `${fname} \u2014 linting\u2026`;
                if (lint.ok) return <>{fname} <CheckCircleIcon size={13} /></>;
                return <>{fname} <XCircleIcon size={13} /> {lint.msg || 'has errors'}</>;
              })()}
            </span>
          </div>
          <div className="cc-footer-btns">
            <ButtonView type="button" variant="ghost" className="dmcr-card-close" iconLeft={<CloseIcon size={12} />} label={saved ? 'Close' : 'Cancel'} onClick={handleClose} />
            {!saved && (
              <ButtonView
                type="button"
                variant="primary"
                iconLeft={<SaveIcon size={13} />}
                label={saving ? 'Saving\u2026' : 'Save to workspace'}
                loading={saving}
                onClick={handleSave}
                disabled={saving || !changeNameValid || dbaName === ''}
                title={!changeNameValid ? 'Fix change name before saving' : dbaName === '' ? 'Set your DBA name in Settings > DMCR Config first' : undefined}
              />
            )}
          </div>
        </div>

        {/* Saved confirmation */}
        {saved && (
          <div className="cc-saved">
            <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2.5" strokeLinecap="round" strokeLinejoin="round"><polyline points="20 6 9 17 4 12"/></svg>
            <span>Saved to</span>
            <span className="cc-saved-path">{saved.folderRel}</span>
            {detailsChanged && (
              <ButtonView type="button" variant="primary" label={savingDetails ? 'Saving details\u2026' : 'Save details'} loading={savingDetails}
                onClick={handleSaveDetails} disabled={savingDetails}
                title="Write the new project, requested by and kind to this change's meta.json (then Commit again)" />
            )}
            <ButtonView type="button" variant="secondary" iconLeft={<FolderOpenIcon size={12} />} label="Reveal in Explorer" onClick={handleReveal} />
            <ButtonView
              type="button"
              variant="secondary"
              color={commitDone ? 'var(--dm-c-4ade80)' : undefined}
              iconLeft={commitDone ? <CheckCircleIcon size={12} /> : <GithubMarkIcon size={13} />}
              label={commitDone ? 'Committed' : committing ? 'Committing\u2026' : 'Commit'}
              loading={committing}
              onClick={handleCommit}
              disabled={committing || commitDone || detailsChanged}
              title={commitDone ? commitInfo : 'Commit (and push when the repository has a remote)'}
            />
          </div>
        )}
        {commitError && (
          <div className="cc-err" style={{ margin: '0 14px 8px' }}>
            <WarningTriangleIcon size={12} style={{ verticalAlign: '-2px', marginRight: 5 }} />Commit failed: {commitError}
            <ButtonView type="button" variant="ghost" label="Dismiss" onClick={() => setCommitError('')} style={{ marginLeft: 8 }} />
          </div>
        )}
      </div>

      {/* Discard warning modal */}
      {showDiscard && (
        <div className="cc-discard-overlay">
          <div className="cc-discard-modal">
            <div className="cc-discard-icon"><WarningTriangleIcon size={28} /></div>
            <div className="cc-discard-title">Discard unsaved changes?</div>
            <div className="cc-discard-msg">Generated SQL has not been saved. You'll be taken back to the form to start over.</div>
            <div className="cc-discard-btns">
              <ButtonView type="button" variant="ghost" label="Keep editing" onClick={handleDiscardCancel} />
              <ButtonView type="button" variant="danger" iconLeft={<TrashIcon size={13} />} label="Discard" onClick={handleDiscardConfirm} />
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
