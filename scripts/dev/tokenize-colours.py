"""
Rewrites every hard-coded colour in webview-ui/src (.css, .tsx) to a palette token:

  #94a3b8              -> var(--dm-c-94a3b8)
  #fff                 -> var(--dm-c-ffffff)
  #6366f180            -> color-mix(in srgb, var(--dm-c-6366f1) 50%, transparent)
  rgba(99,102,241,.12) -> color-mix(in srgb, var(--dm-c-6366f1) 12%, transparent)

Each token defaults to its own value (services/theme/tokens.css), so the app looks exactly the same until a
palette is applied; a palette then recomputes every token from its seeds (services/theme/palette.ts).
Writes services/theme/tokens.css and services/theme/tokens.generated.ts with every token found.
Run from the repo root: python scripts/dev/tokenize-colours.py
"""
import io, os, re, sys

ROOT = os.path.join('webview-ui', 'src')
SKIP_DIRS = {os.path.join(ROOT, 'services', 'theme')}
# the terminal has its own themes (ANSI palettes), handled by the terminal theme code
SKIP_FILES = {os.path.join(ROOT, 'pages', 'runner', n) for n in ('themes.ts', 'VirtualTerm.ts', 'ansi.ts', 'printers.ts')}

found = set()

def tok(hex6):
    hex6 = hex6.lower()
    found.add(hex6)
    return f'var(--dm-c-{hex6})'

def expand(h):
    h = h.lower()
    return ''.join(c * 2 for c in h) if len(h) == 3 else h

def pct(a):
    v = round(float(a) * 100, 2)
    return f'{int(v) if v == int(v) else v}%'

def hex_repl(m):
    h = m.group(1)
    if len(h) == 8:
        return f'color-mix(in srgb, {tok(h[:6])} {pct(int(h[6:], 16) / 255)}, transparent)'
    return tok(expand(h))

def rgb_repl(m):
    r, g, b = (int(float(x)) for x in (m.group(2), m.group(3), m.group(4)))
    h = f'{r:02x}{g:02x}{b:02x}'
    a = m.group(5)
    if a is None or float(a) >= 1:
        return tok(h)
    return f'color-mix(in srgb, {tok(h)} {pct(a)}, transparent)'

RGB = re.compile(r'\b(rgba?)\(\s*(\d{1,3}(?:\.\d+)?)\s*,\s*(\d{1,3}(?:\.\d+)?)\s*,\s*(\d{1,3}(?:\.\d+)?)\s*(?:,\s*(0?\.\d+|1(?:\.0+)?|0|\d?\.\d+))?\s*\)')
# a hex colour: #rgb, #rrggbb or #rrggbbaa, not part of a longer word and not an url(#id) / href="#id"
HEX = re.compile(r'(?<![\w&/])#([0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3})(?![0-9a-zA-Z_-])')

def rewrite_value(v):
    v = RGB.sub(rgb_repl, v)
    return HEX.sub(hex_repl, v)

DECL = re.compile(r'([-\w]+)(\s*:\s*)([^;{}]+)(?=[;}])')

def css_file(text):
    # only declaration values (prop: value;), never selectors: a selector runs into '{', which a value cannot contain
    return DECL.sub(lambda m: m.group(1) + m.group(2) + rewrite_value(m.group(3)), text)

STR = re.compile(r"""('(?:[^'\\\n]|\\.)*'|"(?:[^"\\\n]|\\.)*"|`(?:[^`\\]|\\.)*`)""")

def tsx_file(text):
    def s(m):
        lit = m.group(1)
        body = lit[1:-1]
        # ids and links are not colours
        if re.fullmatch(r'#[\w-]+', body) and not re.fullmatch(r'#(?:[0-9a-fA-F]{3}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})', body):
            return lit
        prev = text[max(0, m.start() - 12):m.start()]
        if re.search(r'(href|xlinkHref|id|key)\s*=\s*\{?$', prev):
            return lit
        if 'url(#' in body:
            body2 = re.sub(r'url\(#[^)]*\)', lambda u: '\x00' + u.group(0)[5:-1] + '\x01', body)
            body2 = rewrite_value(body2)
            body2 = body2.replace('\x00', 'url(#').replace('\x01', ')')
            return lit[0] + body2 + lit[-1]
        return lit[0] + rewrite_value(body) + lit[-1]
    return STR.sub(s, text)

changed = 0
for d, _, files in os.walk(ROOT):
    if any(d.startswith(sd) for sd in SKIP_DIRS):
        continue
    for f in files:
        p = os.path.join(d, f)
        if p in SKIP_FILES or not (f.endswith('.css') or f.endswith('.tsx')):
            continue
        t = io.open(p, encoding='utf-8').read()
        n = css_file(t) if f.endswith('.css') else tsx_file(t)
        if n != t:
            io.open(p, 'w', encoding='utf-8', newline='').write(n)
            changed += 1

theme_dir = os.path.join(ROOT, 'services', 'theme')
toks = sorted(found)
io.open(os.path.join(theme_dir, 'tokens.css'), 'w', encoding='utf-8', newline='').write(
    '/* Generated by scripts/dev/tokenize-colours.py: every colour the UI uses, as a token that defaults to itself.\n'
    '   A palette (services/theme/palette.ts) recomputes them from its seeds. Do not edit by hand. */\n:root {\n'
    + ''.join(f'  --dm-c-{h}: #{h};\n' for h in toks) + '}\n')
io.open(os.path.join(theme_dir, 'tokens.generated.ts'), 'w', encoding='utf-8', newline='').write(
    '// Generated by scripts/dev/tokenize-colours.py: the colour tokens the UI uses (--dm-c-<hex>). Do not edit by hand.\n'
    'export const COLOUR_TOKENS: string[] = [\n' + ''.join(f"  '{h}',\n" for h in toks) + '];\n')
print(f'{changed} files rewritten, {len(toks)} colour tokens')
